; 8086: inverted short condition + near JMP; then a direct far JMP.
STK SEGMENT PARA STACK 'STACK'
    DW 64 DUP (?)
STK ENDS
DAT SEGMENT PARA PUBLIC 'DATA'
    MSG DB 'Jump OK',13,10,'$'
DAT ENDS
ONE SEGMENT PARA PUBLIC 'CODE'
    ASSUME CS:ONE,SS:STK
START:
    MOV AX,1
    CMP AX,0
    JE SHORT SKIP_LONG
NEAR_JUMP:
    JMP NEAR PTR DISTANT
SKIP_LONG:
    MOV AX,4C01H
    INT 21H
    DB 160 DUP (90H)
DISTANT:
    JMP FAR PTR FAR_TARGET
ONE ENDS
TWO SEGMENT PARA PUBLIC 'CODE'
    ASSUME CS:TWO,DS:DAT,SS:STK
FAR_TARGET:
    MOV AX,DAT
    MOV DS,AX
    LEA DX,MSG
    MOV AH,09H
    INT 21H
    MOV AX,4C00H
    INT 21H
TWO ENDS
END START
