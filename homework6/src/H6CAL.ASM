; Calendar, 1900..2099. MASM 5.00, 8086, two code segments.
STACKSEG SEGMENT PARA STACK 'STACK'
    DW 256 DUP (?)
STACKSEG ENDS
DATASEG SEGMENT PARA PUBLIC 'DATA'
    YEAR DW 0
    MONTH DW 0
    DAYS DW 0
    WEEKDAY DW 0
    YPROMPT DB 'Please input year (1900-2099): $'
    MPROMPT DB 'Please input month (1-12): $'
    BADMSG DB 'Invalid input. Please try again.',13,10,'$'
    HEADER DB 'Su Mo Tu We Th Fr Sa',13,10,'$'
    INPUTBUF DB 80,0,80 DUP (0)
    MONTHLEN DB 31,28,31,30,31,30,31,31,30,31,30,31
    NAMES DW OFFSET JAN,OFFSET FEB,OFFSET MAR,OFFSET APR
          DW OFFSET MAY,OFFSET JUN,OFFSET JUL,OFFSET AUG
          DW OFFSET SEP,OFFSET OCT,OFFSET NOV,OFFSET DECEM
    JAN DB 'January$'
    FEB DB 'February$'
    MAR DB 'March$'
    APR DB 'April$'
    MAY DB 'May$'
    JUN DB 'June$'
    JUL DB 'July$'
    AUG DB 'August$'
    SEP DB 'September$'
    OCT DB 'October$'
    NOV DB 'November$'
    DECEM DB 'December$'
DATASEG ENDS

MAINSEG SEGMENT PARA PUBLIC 'CODE'
    ASSUME CS:MAINSEG,DS:DATASEG,SS:STACKSEG
START:
    MOV AX,DATASEG
    MOV DS,AX
YEAR_AGAIN:
    LEA DX,YPROMPT
    MOV CX,4
    CALL READ_NUM
    JC YEAR_BAD
    CMP AX,1900
    JB YEAR_BAD
    CMP AX,2099
    JA YEAR_BAD
    MOV YEAR,AX
    JMP SHORT MONTH_AGAIN
YEAR_BAD:
    LEA DX,BADMSG
    CALL PRINT_STR
    JMP YEAR_AGAIN
MONTH_AGAIN:
    LEA DX,MPROMPT
    MOV CX,2
    CALL READ_NUM
    JC MONTH_BAD
    CMP AX,1
    JB MONTH_BAD
    CMP AX,12
    JA MONTH_BAD
    MOV MONTH,AX
    JMP SHORT CALCULATE
MONTH_BAD:
    LEA DX,BADMSG
    CALL PRINT_STR
    JMP MONTH_AGAIN
CALCULATE:
DATA_CALL:
    CALL FAR PTR GET_DAYS
DATA_RETURN:
    MOV AX,MONTH
    PUSH AX
    MOV AX,YEAR
    PUSH AX
STACK_CALL:
    CALL FAR PTR FIRST_DAY
STACK_RETURN:
    MOV WEEKDAY,AX
    CALL PRINT_CAL
    MOV AX,4C00H
    INT 21H

; DS:DX prompt, CX maximum digits; AX result, CF=1 invalid.
READ_NUM PROC NEAR
    PUSH BX
    PUSH CX
    PUSH DX
    PUSH SI
    PUSH DI
    MOV DI,CX
    CALL PRINT_STR
    MOV BYTE PTR INPUTBUF[1],0
    LEA DX,INPUTBUF
    MOV AH,0AH
    INT 21H
    CALL NEWLINE
    XOR CX,CX
    MOV CL,INPUTBUF[1]
    JCXZ READ_BAD
    CMP CX,DI
    JA READ_BAD
    LEA SI,INPUTBUF[2]
    XOR AX,AX
    MOV BX,10
READ_DIGIT:
    MOV DL,[SI]
    CMP DL,'0'
    JB READ_BAD
    CMP DL,'9'
    JA READ_BAD
    SUB DL,'0'
    XOR DH,DH
    MOV DI,DX
    MUL BX
    ADD AX,DI
    INC SI
    LOOP READ_DIGIT
    CLC
    JMP SHORT READ_DONE
READ_BAD:
    STC
READ_DONE:
    POP DI
    POP SI
    POP DX
    POP CX
    POP BX
    RET
READ_NUM ENDP

; Reads YEAR, MONTH, DAYS, WEEKDAY from the data segment.
PRINT_CAL PROC NEAR
    PUSH AX
    PUSH BX
    PUSH CX
    PUSH DX
    PUSH SI
    CALL NEWLINE
    MOV AX,YEAR
    CALL PRINT_DEC
    MOV DL,' '
    CALL PRINT_CHAR
    CALL PRINT_CHAR
    MOV BX,MONTH
    DEC BX
    SHL BX,1
    MOV DX,NAMES[BX]
    CALL PRINT_STR
    CALL NEWLINE
    LEA DX,HEADER
    CALL PRINT_STR
    MOV CX,WEEKDAY
    JCXZ DATES_BEGIN
LEADING_BLANK:
    MOV DL,' '
    CALL PRINT_CHAR
    CALL PRINT_CHAR
    CALL PRINT_CHAR
    LOOP LEADING_BLANK
DATES_BEGIN:
    MOV SI,1
    MOV BX,WEEKDAY
DATE_LOOP:
    CMP SI,10
    JAE TWO_DIGITS
    MOV DL,' '
    CALL PRINT_CHAR
TWO_DIGITS:
    MOV AX,SI
    CALL PRINT_DEC
    INC BX
    CMP BX,7
    JE WEEK_END
    CMP SI,DAYS
    JE LAST_LINE
    MOV DL,' '
    CALL PRINT_CHAR
    JMP SHORT NEXT_DATE
WEEK_END:
    CALL NEWLINE
    XOR BX,BX
    JMP SHORT NEXT_DATE
LAST_LINE:
    CALL NEWLINE
NEXT_DATE:
    INC SI
    CMP SI,DAYS
    JBE DATE_LOOP
    POP SI
    POP DX
    POP CX
    POP BX
    POP AX
    RET
PRINT_CAL ENDP

; Register parameter AX, all general registers preserved.
PRINT_DEC PROC NEAR
    PUSH AX
    PUSH BX
    PUSH CX
    PUSH DX
    MOV BX,10
    XOR CX,CX
DEC_DIVIDE:
    XOR DX,DX
    DIV BX
    PUSH DX
    INC CX
    OR AX,AX
    JNZ DEC_DIVIDE
DEC_WRITE:
    POP DX
    ADD DL,'0'
    CALL PRINT_CHAR
    LOOP DEC_WRITE
    POP DX
    POP CX
    POP BX
    POP AX
    RET
PRINT_DEC ENDP
PRINT_CHAR PROC NEAR
    PUSH AX
    MOV AH,02H
    INT 21H
    POP AX
    RET
PRINT_CHAR ENDP
PRINT_STR PROC NEAR
    PUSH AX
    MOV AH,09H
    INT 21H
    POP AX
    RET
PRINT_STR ENDP
NEWLINE PROC NEAR
    PUSH DX
    MOV DL,13
    CALL PRINT_CHAR
    MOV DL,10
    CALL PRINT_CHAR
    POP DX
    RET
NEWLINE ENDP
MAINSEG ENDS

CALCSEG SEGMENT PARA PUBLIC 'CODE'
    ASSUME CS:CALCSEG,DS:DATASEG,SS:STACKSEG
; Data-segment parameters and result; DS must already address DATASEG.
GET_DAYS PROC FAR
    PUSH AX
    PUSH BX
    MOV AX,YEAR
    MOV BX,MONTH
    CALL MONTH_DAYS
    MOV DAYS,AX
    POP BX
    POP AX
GET_DAYS_RET:
    RET
GET_DAYS ENDP

; Stack parameters: caller pushes month, then year.
; After PUSH BP: [BP+2] return IP, [BP+4] return CS,
; [BP+6] year, [BP+8] month. Return weekday in AX (Sunday=0).
FIRST_DAY PROC FAR
    PUSH BP
    MOV BP,SP
    PUSH BX
    PUSH CX
    PUSH DX
    PUSH SI
    PUSH DI
    MOV SI,1900
    MOV DI,1
YEAR_LOOP:
    CMP SI,[BP+6]
    JAE YEARS_DONE
    MOV AX,SI
    CALL IS_LEAP
    ADD DI,AX
    INC DI
    CMP DI,7
    JB YEAR_REDUCED
    SUB DI,7
YEAR_REDUCED:
    INC SI
    JMP SHORT YEAR_LOOP
YEARS_DONE:
    MOV BX,1
MONTH_LOOP:
    CMP BX,[BP+8]
    JAE MONTHS_DONE
    MOV AX,[BP+6]
    CALL MONTH_DAYS
    ADD AX,DI
    XOR DX,DX
    MOV CX,7
    DIV CX
    MOV DI,DX
    INC BX
    JMP SHORT MONTH_LOOP
MONTHS_DONE:
    MOV AX,DI
    POP DI
    POP SI
    POP DX
    POP CX
    POP BX
    POP BP
FIRST_DAY_RET:
    RET 4
FIRST_DAY ENDP

; Register parameters AX=year, BX=month (1..12); result AX=days.
MONTH_DAYS PROC NEAR
    PUSH BX
    PUSH DX
    MOV DX,AX
    DEC BX
    XOR AX,AX
    MOV AL,MONTHLEN[BX]
    CMP BX,1
    JNE MD_DONE
    MOV AX,DX
    CALL IS_LEAP
    ADD AX,28
MD_DONE:
    POP DX
    POP BX
    RET
MONTH_DAYS ENDP

; AX year -> AX 0/1. Gregorian rule, including century years.
IS_LEAP PROC NEAR
    PUSH BX
    PUSH CX
    PUSH DX
    MOV CX,AX
    XOR DX,DX
    MOV BX,400
    DIV BX
    OR DX,DX
    JZ LEAP_YES
    MOV AX,CX
    XOR DX,DX
    MOV BX,100
    DIV BX
    OR DX,DX
    JZ LEAP_NO
    MOV AX,CX
    XOR DX,DX
    MOV BX,4
    DIV BX
    OR DX,DX
    JNZ LEAP_NO
LEAP_YES:
    MOV AX,1
    JMP SHORT LEAP_DONE
LEAP_NO:
    XOR AX,AX
LEAP_DONE:
    POP DX
    POP CX
    POP BX
    RET
IS_LEAP ENDP
CALCSEG ENDS
END START
