; Assignment 3: keep the running sum in SS:[BP-2].
.MODEL SMALL
.STACK 100H
.CODE
PUBLIC SUM_DONE,STACK_DONE
START:
    PUSH BP
    MOV BP,SP
    SUB SP,2
    MOV WORD PTR [BP-2],0
    MOV BX,1
    MOV CX,100
SUM_LOOP:
    ADD WORD PTR [BP-2],BX
    INC BX
    LOOP SUM_LOOP
SUM_DONE:
    MOV AX,[BP-2]
    CALL PRINT_DEC
    CALL NEWLINE
    MOV SP,BP
    POP BP
STACK_DONE:
    MOV AX,4C00H
    INT 21H
INCLUDE S3IO.INC
END START
