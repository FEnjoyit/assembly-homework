; Assignment 3: keep the running sum in the data segment.
.MODEL SMALL
.STACK 100H
.DATA
    RESULT DW 0
PUBLIC RESULT
.CODE
PUBLIC SUM_DONE
START:
    MOV AX,@DATA
    MOV DS,AX
    MOV RESULT,0
    MOV BX,1
    MOV CX,100
SUM_LOOP:
    ADD RESULT,BX
    INC BX
    LOOP SUM_LOOP
SUM_DONE:
    MOV AX,RESULT
    CALL PRINT_DEC
    CALL NEWLINE
    MOV AX,4C00H
    INT 21H
INCLUDE S3IO.INC
END START
